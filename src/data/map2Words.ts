import type { VocabWord } from '../types';

export interface Map2LevelData {
  level: number;
  title: string;
  subtitle: string;
  phrase: string;
  words: VocabWord[];
}

function w(id: string, hebrew: string, transliteration: string, translation: string, difficulty: 'easy' | 'medium' | 'hard'): VocabWord {
  return {
    id: `m2-${id}`,
    hebrew,
    transliteration,
    translation,
    mnemonic: '',
    category: 'map2',
    difficulty,
  };
}

